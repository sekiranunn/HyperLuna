import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import compiler from 'vue-template-compiler';
import {patchOfficialScanRate} from './patches/official-scan-rate.mjs';
import {patchAssetPaths} from './patches/asset-paths.mjs';
import {removeFirmwareUi} from './patches/remove-firmware.mjs';
const root = new URL('./', import.meta.url);
mkdirSync(new URL('native', root), {recursive: true});
const original = readFileSync(new URL('official/js/app.1c5e5052.js', root), 'utf8');
const patched = removeFirmwareUi(patchAssetPaths(patchOfficialScanRate(original)));
writeFileSync(new URL('native/official-app.js', root), patched);
const bootstrap = 'new a["default"]({render:e=>e(Gi)}).$mount("#app")';
if (original.split(bootstrap).length !== 2) throw Error('Official application bootstrap changed');
const native = patched.replace(bootstrap, 'window.LunaNative={Vue:a["default"],Header:Li,components:Zi.components}');
writeFileSync(new URL('native/vendor-ui.js', root), native);
const template = readFileSync(new URL('native/research.html', root), 'utf8');
const result = compiler.compile(template, {preserveWhitespace: false});
if (result.errors.length) throw Error(result.errors.join('\n'));
writeFileSync(new URL('native/render.js', root), `// Generated from research.html.\nexport const render = new Function(${JSON.stringify(result.render)});\nexport const staticRenderFns = ${JSON.stringify(result.staticRenderFns)}.map(source => new Function(source));\n`);
const sha = data => createHash('sha256').update(data).digest('hex');
writeFileSync(new URL('native/build-info.json', root), JSON.stringify({official_app_sha256: sha(original), patched_app_sha256: sha(patched), native_adapter_sha256: sha(native), template_sha256: sha(template), vue_compiler: '2.6.12', modification: 'Keep Luna33 button scan rate independent of wired/wireless connection; remove browser cache restoration. Expose existing Vue, Element UI and HeaderMain without mounting the official app on the research page.'}, null, 2));
console.log('Native LunaFury UI adapter and component render functions built.');
