const exact = new Map(messages.map(row => [row[0], row]));
const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const patterns = {code:'[\\dA-Fa-f]{2}',status:'[\\dA-Fa-f]{2}',max:'[\\dA-Fa-f]{2}',
  height:'\\d+(?:\\.\\d+)?',slot:'\\d+',count:'\\d+',address:'[\\dA-Fa-f]{2}:[\\dA-Fa-f]{2}'};
const templates = messages.filter(([key]) => key.includes('{')).map(row => {
  const names = [...row[0].matchAll(/\{(\w+)\}/g)].map(match => match[1]);
  const parts = row[0].split(/\{\w+\}/g).map(escape);
  const pattern = parts.map((part,i) => part + (i < names.length ? `(${patterns[names[i]] || '[\\s\\S]*?'})` : '')).join('');
  return {row, names, pattern:new RegExp(`^${pattern}$`)};
});
export function translate(text, language = 'ZH', values, depth = 0) {
  if (text === null || text === undefined) return '';
  text = String(text);
  const index = languages.indexOf(normalizeLanguage(language));
  let row = exact.get(text), args = values;
  if (!row && index && depth < 6) {
    for (const template of templates) {
      const match = text.match(template.pattern);
      if (!match) continue;
      row = template.row;
      args = Object.fromEntries(template.names.map((name, i) => [name, match[i + 1]]));
      break;
    }
  }
  const result = row ? row[index] : text;
  return args ? result.replace(/\{(\w+)\}/g, (token, name) => name in args ? translate(args[name], language, undefined, depth + 1) : token) : result;
}
