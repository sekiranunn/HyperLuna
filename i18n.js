export const languages = ['ZH', 'EN', 'JPN'];
export const normalizeLanguage = language => languages.includes(language) ? language : 'ZH';
export function savedLanguage(storage) {
  try { return normalizeLanguage((storage === undefined ? globalThis.localStorage : storage)?.getItem('LANG')); } catch { return 'ZH'; }
}
export function applyDocumentLanguage(language) {
  if (typeof document === 'undefined') return;
  const locale = normalizeLanguage(language);
  document.documentElement.lang = {ZH:'zh-CN',EN:'en',JPN:'ja'}[locale];
  document.documentElement.style.setProperty('--fontFamily', {
    ZH:'"MiSans VF", sans-serif',
    EN:'Poppins, "MiSans VF", sans-serif',
    JPN:'"Yu Gothic", "Hiragino Kaku Gothic ProN", Meiryo, sans-serif'
  }[locale]);
}

